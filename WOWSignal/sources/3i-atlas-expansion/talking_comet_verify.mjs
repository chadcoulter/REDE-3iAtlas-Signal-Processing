import fs from "node:fs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
const expectedSourceBlob="f599e1793e856c5023c42976ae3e1b0e2dbb8d90";
const source=fs.readFileSync(new URL("./atlas_phase_feedback.S",import.meta.url));
const gitBlob=createHash("sha1").update(Buffer.from("blob "+source.length+"\0")).update(source).digest("hex");
assert.equal(gitBlob,expectedSourceBlob,"source assembly must match pinned Git blob");
const bytes=fs.readFileSync(new URL("./atlas_phase_feedback.wasm",import.meta.url));
const {instance}=await WebAssembly.instantiate(bytes);
const e=instance.exports;
e.run_reference();
assert.equal(e.trace_words_count(),6400);
const trace=new Uint8Array(e.memory.buffer,e.trace_ptr(),51200);
const expectedHash="e38685a723b769cbb1a573bf8accab0f9064b40d49773b0c5feed16016658d5e";
const actualHash=createHash("sha256").update(trace).digest("hex");
assert.equal(actualHash,expectedHash,"WASM trace must match original native 800-execution trace");
assert.equal(e.resolve(4,8,17,28),0);
assert.equal(e.resolve(32,8,17,28),1);
console.log("Verified 6400 register words against native source trace.");
